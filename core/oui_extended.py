def _clean_oui_table(raw):
    """Normalize prefixes: strip spaces, uppercase, keep only valid 6-hex
    entries. Guards against typos in the table above."""
    import re
    clean = {}
    for prefix, vendor in raw.items():
        p = re.sub(r"[^0-9A-Fa-f]", "", prefix).upper()
        if len(p) == 6:
            clean[p] = vendor
    return clean


